CREATE TRIGGER trg_cache_maintenance
    AFTER INSERT OR UPDATE OR DELETE ON maintenance_block
    FOR EACH ROW EXECUTE FUNCTION refresh_cache_trigger() ;

CREATE TRIGGER trg_cache_item
    AFTER INSERT OR UPDATE OF lifecycle_status ON item
    FOR EACH ROW EXECUTE FUNCTION refresh_cache_trigger() ;

