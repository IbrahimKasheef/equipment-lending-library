-- ---------------------------------------------------------------------------
-- 5. conflict checking across tables (EXCLUDE cannot span tables)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_item_conflicts() RETURNS trigger AS
$$
BEGIN
    -- serialize conflict checks per item
    PERFORM 1 FROM item WHERE item_id = NEW.item_id FOR UPDATE;

    IF TG_TABLE_NAME = 'reservation' THEN
        IF NEW.status = 'HELD' THEN
            IF EXISTS (SELECT 1 FROM item i
                        WHERE i.item_id = NEW.item_id
                          AND i.lifecycle_status IN ('RETIRED','LOST')) THEN
                RAISE EXCEPTION 'ITEM_NOT_LENDABLE (item %)', NEW.item_id USING ERRCODE = '23P01';
            END IF;
            IF EXISTS (SELECT 1 FROM maintenance_block m
                        WHERE m.item_id = NEW.item_id AND m.status = 'ACTIVE'
                          AND m.blocked_range && NEW.reserved_period) THEN
                RAISE EXCEPTION 'CONFLICT_WITH_MAINTENANCE (item %)', NEW.item_id USING ERRCODE = '23P01';
            END IF;
            IF EXISTS (SELECT 1 FROM loan l
                        WHERE l.item_id = NEW.item_id AND l.returned_at IS NULL
                          AND tstzrange(l.checkout_at, l.due_date, '[)') && NEW.reserved_period) THEN
                RAISE EXCEPTION 'CONFLICT_WITH_ACTIVE_LOAN (item %)', NEW.item_id USING ERRCODE = '23P01';
            END IF;
        END IF;

    ELSIF TG_TABLE_NAME = 'maintenance_block' THEN
        IF NEW.status = 'ACTIVE' THEN
            IF EXISTS (SELECT 1 FROM reservation r
                        WHERE r.item_id = NEW.item_id AND r.status = 'HELD'
                          AND r.reserved_period && NEW.blocked_range) THEN
                RAISE EXCEPTION 'CONFLICT_WITH_RESERVATION (item %)', NEW.item_id USING ERRCODE = '23P01';
            END IF;
            IF EXISTS (SELECT 1 FROM loan l
                        WHERE l.item_id = NEW.item_id AND l.returned_at IS NULL
                          AND tstzrange(l.checkout_at, l.due_date, '[)') && NEW.blocked_range) THEN
                RAISE EXCEPTION 'CONFLICT_WITH_ACTIVE_LOAN (item %)', NEW.item_id USING ERRCODE = '23P01';
            END IF;
        END IF;
    END IF;

    RETURN NEW;
END
$$ LANGUAGE plpgsql ;

CREATE TRIGGER trg_conflict_reservation
    BEFORE INSERT OR UPDATE ON reservation
    FOR EACH ROW EXECUTE FUNCTION check_item_conflicts() ;

CREATE TRIGGER trg_conflict_maintenance
    BEFORE INSERT OR UPDATE ON maintenance_block
    FOR EACH ROW EXECUTE FUNCTION check_item_conflicts() ;

-- ---------------------------------------------------------------------------
-- 6. availability cache (triggers + pg_notify)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION refresh_availability_cache(p_item_id integer) RETURNS void AS
$$
DECLARE
    v_lifecycle  item.lifecycle_status%TYPE ;
    v_loan_end   timestamptz ;
    v_overdue    boolean ;
    v_res_end    timestamptz ;
    v_maint_end  timestamptz ;
    v_status     text ;
    v_next       timestamptz ;
BEGIN
    SELECT lifecycle_status INTO v_lifecycle FROM item WHERE item_id = p_item_id ;
    IF NOT FOUND THEN RETURN ; END IF ;

    -- any unreturned loan means the unit is physically out, even past its due date
    SELECT max(l.due_date),
           bool_or(l.due_date < now())
      INTO v_loan_end, v_overdue
      FROM loan l
     WHERE l.item_id = p_item_id AND l.returned_at IS NULL AND l.checkout_at <= now() ;

    SELECT max(upper(r.reserved_period)) INTO v_res_end
      FROM reservation r
     WHERE r.item_id = p_item_id AND r.status = 'HELD' AND r.reserved_period @> now() ;

    SELECT max(upper(m.blocked_range)) INTO v_maint_end
      FROM maintenance_block m
     WHERE m.item_id = p_item_id AND m.status = 'ACTIVE' AND m.blocked_range @> now() ;

    IF v_lifecycle = 'RETIRED' THEN
        v_status := 'RETIRED' ;
    ELSIF v_lifecycle = 'LOST' THEN
        v_status := 'LOST' ;
    ELSIF v_loan_end IS NOT NULL THEN
        v_status := 'ON_LOAN' ;
    ELSIF v_maint_end IS NOT NULL THEN
        v_status := 'MAINTENANCE' ;
    ELSE
        v_status := 'AVAILABLE' ;
    END IF ;

    IF v_status = 'AVAILABLE' THEN
        v_next := now() ;
    ELSIF v_overdue THEN
        v_next := NULL ;               -- unknown until the unit is actually returned
    ELSE
        v_next := GREATEST(COALESCE(v_loan_end,    now()),
                           COALESCE(v_res_end,     now()),
                           COALESCE(v_maint_end,   now())) ;
    END IF ;

    INSERT INTO availability_cache (item_id, cached_status, next_free_ts, last_updated)
    VALUES (p_item_id, v_status, v_next, now())
    ON CONFLICT (item_id) DO UPDATE
       SET cached_status = EXCLUDED.cached_status,
           next_free_ts  = EXCLUDED.next_free_ts,
           last_updated  = now() ;

    IF v_lifecycle NOT IN ('RETIRED','LOST') THEN
        UPDATE item
           SET lifecycle_status = CASE v_status
                   WHEN 'ON_LOAN'     THEN 'ON_LOAN'
                   WHEN 'MAINTENANCE' THEN 'MAINTENANCE'
                   ELSE 'AVAILABLE' END
         WHERE item_id = p_item_id
           AND lifecycle_status IS DISTINCT FROM CASE v_status
                   WHEN 'ON_LOAN'     THEN 'ON_LOAN'
                   WHEN 'MAINTENANCE' THEN 'MAINTENANCE'
                   ELSE 'AVAILABLE' END ;
    END IF ;

    PERFORM pg_notify('availability', p_item_id::text) ;
END
$$ LANGUAGE plpgsql ;

CREATE OR REPLACE FUNCTION refresh_cache_trigger() RETURNS trigger AS
$$
BEGIN
    IF TG_TABLE_NAME = 'item' THEN
        PERFORM refresh_availability_cache(NEW.item_id) ;
        RETURN NULL ;
    END IF ;
    PERFORM refresh_availability_cache(COALESCE(NEW.item_id, OLD.item_id)) ;
    IF TG_OP = 'UPDATE' AND OLD.item_id IS DISTINCT FROM NEW.item_id THEN
        PERFORM refresh_availability_cache(OLD.item_id) ;
    END IF ;
    RETURN NULL ;
END
$$ LANGUAGE plpgsql ;

CREATE TRIGGER trg_cache_reservation
    AFTER INSERT OR UPDATE OR DELETE ON reservation
    FOR EACH ROW EXECUTE FUNCTION refresh_cache_trigger() ;

