CREATE OR REPLACE FUNCTION compute_fine(p_due timestamptz, p_returned timestamptz, p_rate numeric)
RETURNS numeric AS
$$
    SELECT ROUND(GREATEST(0, CEIL(EXTRACT(epoch FROM (p_returned - p_due)) / 86400.0)) * p_rate, 2) ;
$$ LANGUAGE sql IMMUTABLE ;

-- 8.1 FIFO queue: join ------------------------------------------------------
CREATE OR REPLACE FUNCTION join_queue(p_item_id integer, p_request_id integer)
RETURNS integer AS
$$
DECLARE
    v_ticket     integer ;
    v_student    char(10) ;
    v_bad_offers integer ;
BEGIN
    -- serialize ticket allocation per item
    PERFORM 1 FROM item WHERE item_id = p_item_id FOR UPDATE ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ITEM_NOT_FOUND (item %)', p_item_id ;
    END IF ;

    SELECT r.student_id INTO v_student FROM lending_request r WHERE r.request_id = p_request_id ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'REQUEST_NOT_FOUND (request %)', p_request_id ;
    END IF ;

    -- no-show ban rule: too many skipped offers in the recent window
    SELECT count(*) INTO v_bad_offers
      FROM queue_entry qe
      JOIN lending_request r2 ON r2.request_id = qe.request_id
     WHERE r2.student_id = v_student
       AND qe.queue_status = 'SKIPPED'
       AND qe.enqueued_at > now() - (cfg('no_show_window_days') || ' days')::interval ;
    IF v_bad_offers >= cfg('no_show_limit')::int THEN
        RAISE EXCEPTION 'STUDENT_TEMP_BARRED: % no-shows within % days',
              v_bad_offers, cfg('no_show_window_days') ;
    END IF ;

    SELECT COALESCE(MAX(ticket_no), 0) + 1 INTO v_ticket
      FROM queue_entry WHERE item_id = p_item_id ;

    INSERT INTO queue_entry (item_id, ticket_no, request_id)
    VALUES (p_item_id, v_ticket, p_request_id) ;

    RETURN v_ticket ;
END
$$ LANGUAGE plpgsql ;

-- 8.2 FIFO queue: skip expired offers and offer the next in line ------------
CREATE OR REPLACE FUNCTION queue_tick(p_hold_hours numeric DEFAULT NULL)
RETURNS TABLE (item_id integer, ticket_no integer, request_id integer,
               offer_expires_at timestamptz, student_id char(10),
               full_name varchar, purpose text) AS
$$
DECLARE
    v_hold numeric ;
BEGIN
    v_hold := COALESCE(p_hold_hours, cfg('offer_hold_hours')::numeric) ;

    -- 1) expire stale offers -> skipped (no-show)
    UPDATE queue_entry qe
       SET queue_status = 'SKIPPED',
           no_show_count = no_show_count + 1,
           offer_expires_at = NULL
     WHERE qe.queue_status = 'OFFERED'
       AND qe.offer_expires_at < now() ;

    -- 2) offer the first waiting entry for every free item that has no open offer
    RETURN QUERY
    WITH nexts AS (
        SELECT DISTINCT ON (qe.item_id) qe.item_id, qe.ticket_no
          FROM queue_entry qe
          JOIN availability_cache ac ON ac.item_id = qe.item_id
         WHERE qe.queue_status = 'WAITING'
           AND ac.cached_status = 'AVAILABLE'
           AND NOT EXISTS (SELECT 1 FROM queue_entry o
                            WHERE o.item_id = qe.item_id AND o.queue_status = 'OFFERED')
         ORDER BY qe.item_id, qe.ticket_no
    ), offered AS (
        UPDATE queue_entry q
           SET queue_status = 'OFFERED',
               offer_expires_at = now() + (v_hold || ' hours')::interval
          FROM nexts n
         WHERE q.item_id = n.item_id AND q.ticket_no = n.ticket_no
        RETURNING q.item_id, q.ticket_no, q.request_id, q.offer_expires_at
    )
    SELECT o.item_id, o.ticket_no, o.request_id, o.offer_expires_at,
           s.student_id, s.full_name, r.purpose
      FROM offered o
      JOIN lending_request r ON r.request_id = o.request_id
      JOIN student s         ON s.student_id = r.student_id ;
END
$$ LANGUAGE plpgsql ;

-- 8.3 approve a request: auto-reserve, or join the FIFO queue ---------------
CREATE OR REPLACE FUNCTION approve_request(p_request_id integer, p_staff_id integer,
                                           p_item_id integer DEFAULT NULL)
RETURNS jsonb AS
$$
DECLARE
    v_req     lending_request%ROWTYPE ;
    v_item_id integer ;
    v_res_id  integer ;
    v_ticket  integer ;
BEGIN
    SELECT * INTO v_req FROM lending_request WHERE request_id = p_request_id FOR UPDATE ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'REQUEST_NOT_FOUND (request %)', p_request_id ;
    END IF ;
    IF v_req.request_status <> 'PENDING' THEN
        RAISE EXCEPTION 'REQUEST_NOT_PENDING (request % is %)', p_request_id, v_req.request_status ;
    END IF ;

    -- find a lendable unit of the requested model with no conflicting booking;
    -- units that are free right now are preferred over busy ones
    SELECT i.item_id INTO v_item_id
      FROM item i
     WHERE i.model_id = v_req.model_id
       AND (p_item_id IS NULL OR i.item_id = p_item_id)
       AND i.lifecycle_status IN ('AVAILABLE','ON_LOAN')
       AND NOT EXISTS (SELECT 1 FROM reservation r
                        WHERE r.item_id = i.item_id AND r.status = 'HELD'
                          AND r.reserved_period && tstzrange(v_req.requested_start, v_req.requested_end, '[)'))
       AND NOT EXISTS (SELECT 1 FROM maintenance_block m
                        WHERE m.item_id = i.item_id AND m.status = 'ACTIVE'
                          AND m.blocked_range && tstzrange(v_req.requested_start, v_req.requested_end, '[)'))
       AND NOT EXISTS (SELECT 1 FROM loan l
                        WHERE l.item_id = i.item_id AND l.returned_at IS NULL
                          AND tstzrange(l.checkout_at, l.due_date, '[)') &&
                              tstzrange(v_req.requested_start, v_req.requested_end, '[)'))
     ORDER BY (i.lifecycle_status = 'AVAILABLE') DESC, i.item_id
     LIMIT 1 ;

    IF v_item_id IS NOT NULL THEN
        INSERT INTO reservation (request_id, item_id, reserved_period, hold_expires_at)
        VALUES (p_request_id, v_item_id,
                tstzrange(v_req.requested_start, v_req.requested_end, '[)'),
                v_req.requested_start + interval '1 day')
        RETURNING reservation_id INTO v_res_id ;

        UPDATE lending_request SET request_status = 'APPROVED' WHERE request_id = p_request_id ;
        RETURN jsonb_build_object('outcome', 'RESERVED',
                                  'reservation_id', v_res_id,
                                  'item_id', v_item_id) ;
    END IF ;

    -- no free unit for the requested window: join the FIFO queue of the unit
    -- that will free up first (unknown/overdue units go last)
    SELECT i.item_id INTO v_item_id
      FROM item i
      JOIN availability_cache ac ON ac.item_id = i.item_id
     WHERE i.model_id = v_req.model_id
       AND (p_item_id IS NULL OR i.item_id = p_item_id)
       AND i.lifecycle_status IN ('AVAILABLE','ON_LOAN')
     ORDER BY (ac.next_free_ts IS NULL), ac.next_free_ts, i.item_id
     LIMIT 1 ;

    IF v_item_id IS NULL THEN
        RAISE EXCEPTION 'NO_ITEM_FOR_MODEL (model %)', v_req.model_id ;
    END IF ;

    v_ticket := join_queue(v_item_id, p_request_id) ;
    UPDATE lending_request SET request_status = 'APPROVED' WHERE request_id = p_request_id ;
    RETURN jsonb_build_object('outcome', 'QUEUED',
                              'item_id', v_item_id,
                              'ticket_no', v_ticket) ;
END
$$ LANGUAGE plpgsql ;

CREATE OR REPLACE FUNCTION reject_request(p_request_id integer, p_staff_id integer, p_note text DEFAULT NULL)
RETURNS void AS
$$
BEGIN
    UPDATE lending_request
       SET request_status = 'REJECTED',
           remarks = COALESCE(remarks || ' | ', '') || COALESCE(p_note, 'Rejected by staff')
     WHERE request_id = p_request_id AND request_status = 'PENDING' ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'REQUEST_NOT_PENDING (request %)', p_request_id ;
    END IF ;
END
$$ LANGUAGE plpgsql ;

-- 8.4 checkout against a held reservation -----------------------------------
CREATE OR REPLACE FUNCTION checkout(p_reservation_id integer, p_staff_id integer)
RETURNS integer AS          -- returns loan_id
$$
DECLARE
    v_res      reservation%ROWTYPE ;
    v_req      lending_request%ROWTYPE ;
    v_days     smallint ;
    v_loan_id  integer ;
BEGIN
    SELECT * INTO v_res FROM reservation WHERE reservation_id = p_reservation_id FOR UPDATE ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'RESERVATION_NOT_FOUND (reservation %)', p_reservation_id ;
    END IF ;
    IF v_res.status <> 'HELD' THEN
        RAISE EXCEPTION 'RESERVATION_NOT_HELD (reservation % is %)', p_reservation_id, v_res.status ;
    END IF ;
    IF upper(v_res.reserved_period) < now() THEN
        RAISE EXCEPTION 'RESERVATION_EXPIRED (reservation %)', p_reservation_id ;
    END IF ;

    -- serialize per item: concurrent checkouts for the same unit cannot both pass
    PERFORM 1 FROM availability_cache WHERE item_id = v_res.item_id FOR UPDATE ;

    -- the unit must be physically back at the counter and not under maintenance
    IF EXISTS (SELECT 1 FROM loan l
                WHERE l.item_id = v_res.item_id AND l.returned_at IS NULL) THEN
        RAISE EXCEPTION 'ITEM_STILL_ON_LOAN (item %)', v_res.item_id ;
    END IF ;
    IF EXISTS (SELECT 1 FROM maintenance_block m
                WHERE m.item_id = v_res.item_id AND m.status = 'ACTIVE'
                  AND m.blocked_range @> now()) THEN
        RAISE EXCEPTION 'ITEM_UNDER_MAINTENANCE (item %)', v_res.item_id ;
    END IF ;

    SELECT r.* INTO v_req FROM lending_request r WHERE r.request_id = v_res.request_id ;

    SELECT c.max_loan_days INTO v_days
      FROM item i
      JOIN equipment e ON e.model_id = i.model_id
      JOIN category  c ON c.category_id = e.category_id
     WHERE i.item_id = v_res.item_id ;

    INSERT INTO loan (reservation_id, student_id, item_id, issued_by_staff_id, due_date)
    VALUES (v_res.reservation_id, v_req.student_id, v_res.item_id, p_staff_id,
            now() + (v_days || ' days')::interval)
    RETURNING loan_id INTO v_loan_id ;

    UPDATE reservation      SET status = 'FULFILLED'  WHERE reservation_id = p_reservation_id ;
    UPDATE lending_request  SET request_status = 'FULFILLED' WHERE request_id = v_res.request_id ;

    RETURN v_loan_id ;
END
$$ LANGUAGE plpgsql ;

-- 8.5 walk-in checkout (no reservation): the classic "two requests, one unit" case
CREATE OR REPLACE FUNCTION checkout_walkin(p_student_id char(10), p_item_id integer, p_staff_id integer)
RETURNS integer AS          -- returns loan_id
$$
DECLARE
    v_status  varchar(15) ;
    v_days    smallint ;
    v_loan_id integer ;
BEGIN
    -- serialize on the cache row: the second concurrent session must wait / retry
    SELECT ac.cached_status, c.max_loan_days
      INTO v_status, v_days
      FROM availability_cache ac
      JOIN item i      ON i.item_id = ac.item_id
      JOIN equipment e ON e.model_id = i.model_id
      JOIN category  c ON c.category_id = e.category_id
     WHERE ac.item_id = p_item_id
     FOR UPDATE OF ac ;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'ITEM_NOT_FOUND (item %)', p_item_id ;
    END IF ;
    IF v_status <> 'AVAILABLE' THEN
        RAISE EXCEPTION 'ITEM_NOT_AVAILABLE (item % is %)', p_item_id, v_status ;
    END IF ;

    INSERT INTO loan (student_id, item_id, issued_by_staff_id, due_date)
    VALUES (p_student_id, p_item_id, p_staff_id,
            now() + (v_days || ' days')::interval)
    RETURNING loan_id INTO v_loan_id ;

    RETURN v_loan_id ;
END
$$ LANGUAGE plpgsql ;

-- 8.6 return ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION return_item(p_loan_id integer, p_condition varchar, p_staff_id integer)
RETURNS loan AS
$$
DECLARE
    v_loan loan%ROWTYPE ;
    v_rate numeric ;
    v_out  loan%ROWTYPE ;
BEGIN
    SELECT * INTO v_loan FROM loan WHERE loan_id = p_loan_id FOR UPDATE ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'LOAN_NOT_FOUND (loan %)', p_loan_id ;
    END IF ;
    IF v_loan.returned_at IS NOT NULL THEN
        RAISE EXCEPTION 'LOAN_ALREADY_RETURNED (loan %)', p_loan_id ;
    END IF ;

    SELECT c.late_fee_per_day INTO v_rate
      FROM item i
      JOIN equipment e ON e.model_id = i.model_id
      JOIN category  c ON c.category_id = e.category_id
     WHERE i.item_id = v_loan.item_id ;

    UPDATE loan
       SET returned_at      = now(),
           return_condition = p_condition,
           loan_status      = 'RETURNED',
           fine_amount      = compute_fine(due_date, now(), v_rate)
     WHERE loan_id = p_loan_id
    RETURNING * INTO v_out ;

    RETURN v_out ;
END
$$ LANGUAGE plpgsql ;

-- 8.7 overdue escalation (run nightly by pg_cron; called by the API for demos)
CREATE OR REPLACE FUNCTION escalate_overdue()
RETURNS integer AS
$$
DECLARE
    v_n integer ;
BEGIN
    WITH upd AS (
        UPDATE loan l
           SET loan_status = 'OVERDUE',
               fine_amount = compute_fine(l.due_date, now(),
                              (SELECT c.late_fee_per_day
                                 FROM item i
                                 JOIN equipment e ON e.model_id = i.model_id
                                 JOIN category  c ON c.category_id = e.category_id
                                WHERE i.item_id = l.item_id))
         WHERE l.returned_at IS NULL AND l.loan_status = 'ACTIVE' AND now() > l.due_date
        RETURNING 1)
    SELECT count(*) INTO v_n FROM upd ;

    -- after the configurable grace period the unit is declared LOST
    UPDATE loan l
       SET loan_status = 'LOST'
     WHERE l.returned_at IS NULL AND l.loan_status = 'OVERDUE'
       AND now() > l.due_date + (cfg('lost_after_days') || ' days')::interval ;

    -- reflect lost units on the item itself (cache refresh picks this up)
    UPDATE item i
       SET lifecycle_status = 'LOST'
     WHERE lifecycle_status <> 'LOST'
       AND EXISTS (SELECT 1 FROM loan l
                    WHERE l.item_id = i.item_id AND l.loan_status = 'LOST' AND l.returned_at IS NULL) ;

    RETURN v_n ;
END
$$ LANGUAGE plpgsql ;

