CREATE OR REPLACE VIEW v_availability AS
SELECT i.item_id, i.serial_no, i.item_condition, i.lifecycle_status,
       e.model_id, e.model_name, e.manufacturer,
       c.category_id, c.category_name, c.max_loan_days, c.late_fee_per_day,
       d.dept_id, d.dept_name,
       COALESCE(ac.cached_status, i.lifecycle_status) AS availability,
       ac.next_free_ts, ac.last_updated
  FROM item i
  JOIN equipment  e ON e.model_id    = i.model_id
  JOIN category   c ON c.category_id = e.category_id
  JOIN department d ON d.dept_id     = i.dept_id
  LEFT JOIN availability_cache ac ON ac.item_id = i.item_id ;

CREATE OR REPLACE VIEW v_calendar AS
    SELECT item_id, 'LOAN'::text AS kind, loan_id::text AS ref_id,
           checkout_at AS start_ts, COALESCE(returned_at, due_date) AS end_ts,
           loan_status::text AS status
      FROM loan
UNION ALL
    SELECT item_id, 'RESERVATION', reservation_id::text,
           lower(reserved_period), upper(reserved_period), status
      FROM reservation
UNION ALL
    SELECT item_id, 'MAINTENANCE', block_id::text,
           lower(blocked_range), upper(blocked_range), status
      FROM maintenance_block ;

CREATE OR REPLACE VIEW v_queue_board AS
SELECT qe.item_id, i.serial_no, e.model_name,
       qe.ticket_no, qe.request_id, s.student_id, s.full_name,
       qe.enqueued_at, qe.queue_status, qe.offer_expires_at, qe.no_show_count,
       r.purpose
  FROM queue_entry qe
  JOIN item i             ON i.item_id    = qe.item_id
  JOIN equipment e        ON e.model_id   = i.model_id
  JOIN lending_request r  ON r.request_id = qe.request_id
  JOIN student s          ON s.student_id = r.student_id ;

CREATE OR REPLACE VIEW v_overdue AS
SELECT l.loan_id, i.item_id, i.serial_no, e.model_name,
       s.student_id, s.full_name, d.dept_name,
       l.checkout_at, l.due_date,
       CEIL(EXTRACT(epoch FROM (now() - l.due_date)) / 86400.0)::int AS days_overdue,
       compute_fine(l.due_date, now(), c.late_fee_per_day)           AS projected_fine,
       l.fine_amount, l.loan_status
  FROM loan l
  JOIN item i             ON i.item_id    = l.item_id
  JOIN equipment e        ON e.model_id   = i.model_id
  JOIN category c         ON c.category_id = e.category_id
  JOIN student s          ON s.student_id = l.student_id
  JOIN department d       ON d.dept_id    = s.dept_id
 WHERE l.returned_at IS NULL AND now() > l.due_date
   AND l.loan_status IN ('ACTIVE','OVERDUE','LOST') ;

CREATE OR REPLACE VIEW v_item_utilization AS
SELECT i.item_id, i.serial_no, e.model_name, d.dept_name,
       w.win_start,
       ROUND(EXTRACT(epoch FROM (now() - w.win_start)) / 3600.0, 1) AS window_hours,
       ROUND((COALESCE(l.busy_s, 0) + COALESCE(m.busy_s, 0)) / 3600.0, 1) AS busy_hours,
       ROUND(100.0 * (COALESCE(l.busy_s, 0) + COALESCE(m.busy_s, 0))
             / NULLIF(EXTRACT(epoch FROM (now() - w.win_start)), 0), 1) AS utilization_pct
  FROM item i
  JOIN equipment  e ON e.model_id = i.model_id
  JOIN department d ON d.dept_id  = i.dept_id
  CROSS JOIN LATERAL (
       SELECT GREATEST(now() - interval '90 days', i.purchase_date::timestamptz) AS win_start
  ) w
  LEFT JOIN LATERAL (
       SELECT SUM(EXTRACT(epoch FROM (COALESCE(ln.returned_at, now()) - GREATEST(ln.checkout_at, w.win_start)))) AS busy_s
         FROM loan ln
        WHERE ln.item_id = i.item_id
          AND ln.checkout_at < now()
          AND COALESCE(ln.returned_at, ln.due_date) > w.win_start
  ) l ON true
  LEFT JOIN LATERAL (
       SELECT SUM(EXTRACT(epoch FROM (LEAST(upper(mb.blocked_range), now()) - GREATEST(lower(mb.blocked_range), w.win_start)))) AS busy_s
         FROM maintenance_block mb
        WHERE mb.item_id = i.item_id
          AND mb.status IN ('ACTIVE','DONE')
          AND lower(mb.blocked_range) < now()
          AND upper(mb.blocked_range) > w.win_start
  ) m ON true ;

CREATE OR REPLACE VIEW v_dept_utilization AS
SELECT dept_name,
       count(*)                                AS item_count,
       ROUND(avg(utilization_pct), 1)          AS avg_utilization_pct,
       ROUND(sum(busy_hours), 1)               AS total_busy_hours,
       ROUND(sum(window_hours), 1)             AS total_window_hours
  FROM v_item_utilization
 GROUP BY dept_name
 ORDER BY avg_utilization_pct DESC ;

CREATE OR REPLACE VIEW v_idle_items AS
SELECT item_id, serial_no, model_name, dept_name, utilization_pct, busy_hours, window_hours
  FROM v_item_utilization
 WHERE utilization_pct < 5
 ORDER BY utilization_pct, serial_no ;

