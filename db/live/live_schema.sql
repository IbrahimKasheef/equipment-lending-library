-- ============================================================================
--  EQUIPMENT LENDING LIBRARY - LIVE WEBSITE SCHEMA (PostgreSQL 16)
--
--  Extends the core schema (../schema.sql) with everything the live website
--  needs on top of the demo schema:
--    * labs and department-owned equipment (college-wide)
--    * items assigned to a lab
--    * student accounts + faculty accounts (bcrypt via pgcrypto)
--    * database-backed sessions for the web login
--    * student-initiated "request return" workflow on loans
--    * item add / retire (soft remove) / restore helpers
--
--  Usage:
--    psql -U postgres -p 5433 -d lending_library_live -v ON_ERROR_STOP=1 -f db/live/live_schema.sql
--
--  The core DDL in ../schema.sql is included first, so this file is the single
--  build script for the live database (fresh, destructive rebuild).
-- ============================================================================

SET client_min_messages = warning;

-- drop live-only objects first (they depend on the core tables, which
-- ../schema.sql drops and recreates below)
DROP VIEW     IF EXISTS v_student_loans, v_lab_items CASCADE;
DROP TABLE    IF EXISTS app_session, app_user, lab CASCADE;
DROP FUNCTION IF EXISTS request_return(integer, character) CASCADE;
DROP FUNCTION IF EXISTS cancel_return_request(integer, character) CASCADE;
DROP FUNCTION IF EXISTS retire_item(integer, integer) CASCADE;
DROP FUNCTION IF EXISTS unretire_item(integer) CASCADE;

-- ---- the core schema (tables, constraints, functions, views) --------------
\ir ../schema.sql

SET client_min_messages = warning;

BEGIN;

-- ---------------------------------------------------------------------------
-- 1a. college-wide departments (branch code drives the student email/USN rule)
-- ---------------------------------------------------------------------------
ALTER TABLE department ADD COLUMN branch_code varchar(4) UNIQUE ;
CREATE INDEX idx_department_branch ON department(branch_code) ;

-- ---------------------------------------------------------------------------
-- 1. accounts, sessions (bcrypt hashes via pgcrypto)
-- ---------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE app_user (
    user_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(120) NOT NULL CHECK (email = lower(email)),
    password_hash text        NOT NULL,                    -- crypt(pw, gen_salt('bf'))
    role          varchar(10) NOT NULL CHECK (role IN ('STUDENT','FACULTY','ADMIN')),
    student_id    char(10) REFERENCES student(student_id) ON DELETE CASCADE,
    staff_id      integer  REFERENCES staff(staff_id)     ON DELETE CASCADE,
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_login    timestamptz,
    CHECK ((role = 'STUDENT') = (student_id IS NOT NULL)),
    CHECK ((role IN ('FACULTY','ADMIN')) = (staff_id IS NOT NULL))
) ;

CREATE UNIQUE INDEX app_user_email_uq ON app_user (lower(email)) ;

-- ---------------------------------------------------------------------------
-- 1b. RVCE email structure (database-enforced)
--     students : full name (no dots) + .<branch><batch>@rvce.edu.in
--                e.g. ibrahimkasheef.is24@rvce.edu.in
--     faculty  : their college mailbox, no batch/branch suffix (no fixed
--                convention; dots are allowed, e.g. rashmir@rvce.edu.in)
-- ---------------------------------------------------------------------------
ALTER TABLE student
    ADD CONSTRAINT student_college_email_chk
    CHECK (email ~ '^[a-z0-9]+\.[a-z]{2}[0-9]{2}@rvce\.edu\.in$') ;

ALTER TABLE app_user
    ADD CONSTRAINT app_user_email_role_chk
    CHECK (
        (role = 'STUDENT' AND email ~ '^[a-z0-9]+\.[a-z]{2}[0-9]{2}@rvce\.edu\.in$')
        OR
        (role IN ('FACULTY','ADMIN') AND email ~ '^[a-z0-9._%+-]+@rvce\.edu\.in$')
    ) ;

CREATE TABLE app_session (
    token_hash text        PRIMARY KEY,                    -- sha256 of the bearer token
    user_id    integer     NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    last_seen  timestamptz NOT NULL DEFAULT now()
) ;

CREATE INDEX idx_session_user   ON app_session(user_id) ;
CREATE INDEX idx_session_expiry ON app_session(expires_at) ;

-- The live registration form does not ask for a semester; the department can
-- fill it in later.
ALTER TABLE student ALTER COLUMN semester DROP NOT NULL ;

-- ---------------------------------------------------------------------------
-- 2. labs (each lab belongs to a department; seeded college-wide)
-- ---------------------------------------------------------------------------
CREATE TABLE lab (
    lab_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_name varchar(80) NOT NULL UNIQUE,
    dept_id  integer     NOT NULL REFERENCES department(dept_id),
    location varchar(60)
) ;

ALTER TABLE item ADD COLUMN lab_id integer REFERENCES lab(lab_id) ;
CREATE INDEX idx_item_lab ON item(lab_id) ;

-- Equipment models belong to exactly one department; labs and models must
-- agree. All participating labs belong to a department as well.
ALTER TABLE equipment ADD COLUMN dept_id integer REFERENCES department(dept_id) ;
CREATE INDEX idx_equipment_dept ON equipment(dept_id) ;
ALTER TABLE equipment DROP CONSTRAINT IF EXISTS equipment_model_name_manufacturer_key ;
ALTER TABLE equipment
    ADD CONSTRAINT equipment_model_dept_uq UNIQUE (model_name, manufacturer, dept_id) ;

-- ---------------------------------------------------------------------------
-- 3. student-initiated return requests
-- ---------------------------------------------------------------------------
ALTER TABLE loan ADD COLUMN return_requested_at timestamptz ;
ALTER TABLE loan ADD COLUMN return_request_note text ;
CREATE INDEX idx_loan_student        ON loan(student_id) ;
CREATE INDEX idx_loan_return_request ON loan(return_requested_at) WHERE return_requested_at IS NOT NULL ;

CREATE OR REPLACE FUNCTION request_return(p_loan_id integer, p_student_id char(10))
RETURNS loan AS
$$
DECLARE
    v_loan loan%ROWTYPE ;
BEGIN
    SELECT * INTO v_loan FROM loan WHERE loan_id = p_loan_id FOR UPDATE ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'LOAN_NOT_FOUND (loan %)', p_loan_id ;
    END IF ;
    IF v_loan.student_id <> p_student_id THEN
        RAISE EXCEPTION 'NOT_YOUR_LOAN (loan %)', p_loan_id ;
    END IF ;
    IF v_loan.returned_at IS NOT NULL THEN
        RAISE EXCEPTION 'LOAN_ALREADY_RETURNED (loan %)', p_loan_id ;
    END IF ;
    IF v_loan.return_requested_at IS NOT NULL THEN
        RAISE EXCEPTION 'RETURN_ALREADY_REQUESTED (loan %)', p_loan_id ;
    END IF ;

    UPDATE loan
       SET return_requested_at = now()
     WHERE loan_id = p_loan_id
    RETURNING * INTO v_loan ;
    RETURN v_loan ;
END
$$ LANGUAGE plpgsql ;

CREATE OR REPLACE FUNCTION cancel_return_request(p_loan_id integer, p_student_id char(10))
RETURNS loan AS
$$
DECLARE
    v_loan loan%ROWTYPE ;
BEGIN
    SELECT * INTO v_loan FROM loan WHERE loan_id = p_loan_id FOR UPDATE ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'LOAN_NOT_FOUND (loan %)', p_loan_id ;
    END IF ;
    IF v_loan.student_id <> p_student_id THEN
        RAISE EXCEPTION 'NOT_YOUR_LOAN (loan %)', p_loan_id ;
    END IF ;
    IF v_loan.returned_at IS NOT NULL THEN
        RAISE EXCEPTION 'LOAN_ALREADY_RETURNED (loan %)', p_loan_id ;
    END IF ;
    IF v_loan.return_requested_at IS NULL THEN
        RAISE EXCEPTION 'RETURN_NOT_REQUESTED (loan %)', p_loan_id ;
    END IF ;

    UPDATE loan
       SET return_requested_at = NULL,
           return_request_note = NULL
     WHERE loan_id = p_loan_id
    RETURNING * INTO v_loan ;
    RETURN v_loan ;
END
$$ LANGUAGE plpgsql ;

-- ---------------------------------------------------------------------------
-- 4. item management helpers (faculty "add / remove" from the live site)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION retire_item(p_item_id integer, p_staff_id integer)
RETURNS void AS
$$
BEGIN
    PERFORM 1 FROM item WHERE item_id = p_item_id FOR UPDATE ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ITEM_NOT_FOUND (item %)', p_item_id ;
    END IF ;

    IF EXISTS (SELECT 1 FROM loan l WHERE l.item_id = p_item_id AND l.returned_at IS NULL) THEN
        RAISE EXCEPTION 'ITEM_ON_LOAN (item %)', p_item_id ;
    END IF ;
    IF EXISTS (SELECT 1 FROM reservation r
                WHERE r.item_id = p_item_id AND r.status = 'HELD'
                  AND upper(r.reserved_period) > now()) THEN
        RAISE EXCEPTION 'ITEM_HAS_FUTURE_RESERVATION (item %)', p_item_id ;
    END IF ;
    IF EXISTS (SELECT 1 FROM maintenance_block m
                WHERE m.item_id = p_item_id AND m.status = 'ACTIVE'
                  AND upper(m.blocked_range) > now()) THEN
        RAISE EXCEPTION 'ITEM_HAS_ACTIVE_MAINTENANCE (item %)', p_item_id ;
    END IF ;

    UPDATE item SET lifecycle_status = 'RETIRED'
     WHERE item_id = p_item_id AND lifecycle_status <> 'RETIRED' ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ITEM_ALREADY_RETIRED (item %)', p_item_id ;
    END IF ;
END
$$ LANGUAGE plpgsql ;

CREATE OR REPLACE FUNCTION unretire_item(p_item_id integer)
RETURNS void AS
$$
BEGIN
    PERFORM 1 FROM item WHERE item_id = p_item_id FOR UPDATE ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ITEM_NOT_FOUND (item %)', p_item_id ;
    END IF ;

    UPDATE item SET lifecycle_status = 'AVAILABLE'
     WHERE item_id = p_item_id AND lifecycle_status = 'RETIRED' ;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'ITEM_NOT_RETIRED (item %)', p_item_id ;
    END IF ;
END
$$ LANGUAGE plpgsql ;

-- ---------------------------------------------------------------------------
-- 5. live views
-- ---------------------------------------------------------------------------
-- every item together with its lab (for the equipment management page)
CREATE OR REPLACE VIEW v_lab_items AS
SELECT va.item_id, va.serial_no, va.item_condition, va.lifecycle_status,
       va.model_id, va.model_name, va.manufacturer,
       va.category_id, va.category_name, va.max_loan_days, va.late_fee_per_day,
       va.dept_id, va.dept_name, va.availability, va.next_free_ts, va.last_updated,
       i.lab_id, l.lab_name, l.location
  FROM v_availability va
  JOIN item i ON i.item_id = va.item_id
  JOIN lab  l ON l.lab_id  = i.lab_id ;

-- one row per loan with everything the student/faculty pages need
CREATE OR REPLACE VIEW v_student_loans AS
SELECT l.loan_id, l.student_id, s.full_name, s.email,
       l.item_id, i.serial_no, i.lab_id, lab.lab_name,
       e.model_id, e.model_name, e.manufacturer, e.dept_id, dep.dept_name,
       l.checkout_at, l.due_date, l.returned_at, l.return_condition,
       l.loan_status, l.fine_amount, l.return_requested_at, l.return_request_note,
       CASE WHEN l.returned_at IS NULL AND now() > l.due_date
            THEN floor(EXTRACT(epoch FROM (now() - l.due_date)) / 86400.0)::int
            ELSE 0 END AS days_overdue
  FROM loan l
  JOIN student  s   ON s.student_id = l.student_id
  JOIN item     i   ON i.item_id    = l.item_id
  JOIN equipment e  ON e.model_id   = i.model_id
  LEFT JOIN department dep ON dep.dept_id = e.dept_id
  LEFT JOIN lab     ON lab.lab_id   = i.lab_id ;

-- audit item lifecycle changes (who added / retired a unit)
CREATE TRIGGER trg_audit_item
    AFTER INSERT OR UPDATE OR DELETE ON item
    FOR EACH ROW EXECUTE FUNCTION audit_row('item_id') ;

COMMIT;
